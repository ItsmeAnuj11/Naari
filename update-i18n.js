// 2. Update Components
function processComponent(filepath, replacements, requiresI18nHook) {
    if (!fs.existsSync(filepath)) return;
    let code = fs.readFileSync(filepath, 'utf8');
    
    // Add useLanguage if not present
    if (requiresI18nHook && !code.includes('useLanguage')) {
        code = code.replace(/import React(.*?);/, `import React$1;\nimport { useLanguage } from '@/lib/i18n';`);
    }

    if (requiresI18nHook && !code.includes('const { t } = useLanguage()')) {
      // Find the first component definition to inject the hook
      code = code.replace(/export function (\w+)\(([^)]*)\) \{/, `export function $1($2) {\n  const { t } = useLanguage();`);
    }

    for (const [hindi, translation] of Object.entries(replacements)) {
      if (typeof translation === 'string') {
        // Just standard string replace
        code = code.split(hindi).join(`{t('${hindi}')}`);
      } else if (translation.exact) {
        // e.g. for "मदद चाहिए?"
        code = code.split(translation.exact).join(translation.replace);
      }
    }

    fs.writeFileSync(filepath, code, 'utf8');
}

