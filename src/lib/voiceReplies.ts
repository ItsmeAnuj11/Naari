export function getSpeechReply(text: string, selectedLocale: Locale) {
  const spokenLocale: Locale = /[\u0B80-\u0BFF]/.test(text) ? 'ta'
    : /[\u0C00-\u0C7F]/.test(text) ? 'te'
      : /[\u0900-\u097F]/.test(text) ? (selectedLocale === 'awa' || selectedLocale === 'bho' ? selectedLocale : 'hi')
        : /[a-zA-Z]/.test(text) ? 'en' : selectedLocale;
  const query = text.toLocaleLowerCase();
  const topic = /pmmvy|matru|maternity|கர்ப்ப|தாய்மை|மாத்ரு|గర్భ|మాతృ/.test(query) ? 'maternity'
    : /ujjwala|gas|lpg|எரிவாயு|சமையல்|ఉజ్వల|గ్యాస్/.test(query) ? 'gas'
      : /kisan|farmer|किसान|விவசாய|రైతు|వ్యవసாய/.test(query) ? 'farmer'
        : /sukanya|girl|daughter|பெண் குழந்தை|சுகன்யா|బాలిక|సుకన్య/.test(query) ? 'girl'
          : /ayushman|health|hospital|மருத்துவ|ஆயுஷ்மான்|ఆరోగ్య|ఆయుష్మాన్/.test(query) ? 'health' : 'general';
  return { text: replies[spokenLocale][topic], locale: spokenLocale, language: languages[spokenLocale] };
}
